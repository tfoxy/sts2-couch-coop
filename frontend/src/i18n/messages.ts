export type MessageKey = keyof typeof en;
type LocaleCatalog = { [Key in MessageKey]: string };

function preservePlaceholders(catalog: LocaleCatalog): LocaleCatalog {
  const aligned = { ...catalog };
  for (const key of Object.keys(en) as MessageKey[]) {
    const expected = [...en[key].matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
    for (const match of en[key].matchAll(/\{(\w+)\}/g)) {
      aligned[key] = aligned[key].replace(new RegExp(`\\{${match[1]}\\}`, "gi"), `{${match[1]}}`);
    }
    aligned[key] = aligned[key].replace(/\{(\w+)\}/g, (whole, name: string) => expected.includes(name) ? whole : "");
    for (const name of expected) {
      if (!aligned[key].includes(`{${name}}`)) aligned[key] += ` {${name}}`;
    }
  }
  return aligned;
}

