    // Every value-type field at its client fallback default is OMITTED (nulled by the DTO → WhenWritingNull).
    private static void DefaultValuedFieldsAreOmitted()
    {
        // A node with EVERY omittable field at its default. Only id/name/nodeType survive.
        var node = Node("a"); // Visible true, Opacity 1, Scale 1, Pivot 0, NinePatch false, etc.
        var json = Serialize(Delta(node));
        foreach (var omitted in new[]
        {
            "\"visible\"", "\"opacity\"", "\"scaleX\"", "\"scaleY\"", "\"pivotX\"", "\"pivotY\"",
            "\"ninePatch\"", "\"showBehindParent\"", "\"clipChildren\"", "\"focused\"", "\"richText\"",
            "\"textureFlipH\"", "\"textureFlipV\"", "\"particleEmitting\"", "\"particleRestartEpoch\"",
            "\"spineTrackTime\"", "\"spineLooping\"", "\"rotation\"", "\"zIndex\"",
        })
        {
            Assert(!json.Contains(omitted, StringComparison.Ordinal), $"default-valued field {omitted} omitted");
        }
        Assert(json.Contains("\"id\":\"a\"", StringComparison.Ordinal), "id always written");
    }

    // Meaningful non-default value types are WRITTEN (a blanket WhenWritingDefault would WRONGLY drop these).
    private static void MeaningfulNonDefaultsAreWritten()
    {
        var node = Node("a") with { Visible = false, Opacity = 0, SpineLooping = false, NinePatch = true };
        var json = Serialize(Delta(node));
        Assert(json.Contains("\"visible\":false", StringComparison.Ordinal), "visible:false written (not the true default)");
        Assert(json.Contains("\"opacity\":0", StringComparison.Ordinal), "opacity:0 written (not the 1 default)");
        Assert(json.Contains("\"spineLooping\":false", StringComparison.Ordinal), "spineLooping:false written (not the true default)");
        Assert(json.Contains("\"ninePatch\":true", StringComparison.Ordinal), "ninePatch:true written");
        Assert(!json.Contains("\"rotation\"", StringComparison.Ordinal), "dead rotation field killed end-to-end");
    }

    // R13 CONTENT KEY: WireNodeDelta is an EXPLICIT field-by-field projection of the producer's node, so a new
    // producer field is SILENTLY DROPPED unless FromNode lists it (the PinnedLoopAnim lesson). Prove the pooled-card
    // content identity reaches the wire under its camelCase name — `contentKey` is the property the client keys its
    // pool-recycling DOM adoption on — and that a node without one (almost all of them) still omits the field.
    private static void ContentKeyReachesTheWire()
    {
        var json = Serialize(Delta(Node("card") with { ContentKey = "nc:Strike#12" }));
        Assert(json.Contains("\"contentKey\":\"nc:Strike#12\"", StringComparison.Ordinal),
            $"content key projected onto the wire; got: {json}");

        Assert(!Serialize(Delta(Node("a"))).Contains("\"contentKey\"", StringComparison.Ordinal),
            "content key omitted when the producer sent none");
    }

    // PER-ROLE RICH-TEXT FONTS: same lesson as ContentKey — WireNodeDelta is an EXPLICIT field-by-field projection,
    // so a producer field the client's reader is already waiting for is SILENTLY DROPPED unless FromNode lists it.
    // The three-way static-field lockstep can't catch that: it reflects over RuntimeSceneNodeDelta (the producer
    // record), never over the wire DTO. Prove all nine reach the wire under the camelCase names sceneTree.ts /
    // SceneDeltaReader read, in the shapes they read them in (a slimmed `{resourcePath}` for the fonts, bare numbers
    // for the scalars) — and that a node with none of them (essentially every node) still omits all nine, so the
    // wire off the rich-text scenes is byte-identical.
    private static void RichRoleFontsReachTheWire()
    {
        var node = Node("title") with
        {
            RichText = true,
            RichBoldFont = new RuntimeSceneResourceRefSnapshot("Theme", "res://fonts/kreon_bold.ttf", "FontFile", "bold"),
            RichItalicFont = new RuntimeSceneResourceRefSnapshot("Theme", "res://fonts/kreon_italic.ttf", "FontFile", "it"),
            RichBoldItalicFont = new RuntimeSceneResourceRefSnapshot("Theme", "res://fonts/kreon_bold_italic.ttf", "FontFile", "bi"),
            RichBoldFontSizePx = 21,
            RichItalicFontSizePx = 22,
            RichBoldItalicFontSizePx = 23,
            RichBoldFontSpacingPx = 1,
            RichItalicFontSpacingPx = 2,
            RichBoldItalicFontSpacingPx = 3,
        };
        var json = Serialize(Delta(node));

        Assert(json.Contains("\"richBoldFont\":{\"resourcePath\":\"res://fonts/kreon_bold.ttf\"}", StringComparison.Ordinal),
            $"richBoldFont projected onto the wire as a slimmed resource ref; got: {json}");
        Assert(json.Contains("\"richItalicFont\":{\"resourcePath\":\"res://fonts/kreon_italic.ttf\"}", StringComparison.Ordinal),
            "richItalicFont projected onto the wire");
        Assert(json.Contains("\"richBoldItalicFont\":{\"resourcePath\":\"res://fonts/kreon_bold_italic.ttf\"}", StringComparison.Ordinal),
            "richBoldItalicFont projected onto the wire");
        Assert(json.Contains("\"richBoldFontSizePx\":21", StringComparison.Ordinal), "richBoldFontSizePx on the wire");
        Assert(json.Contains("\"richItalicFontSizePx\":22", StringComparison.Ordinal), "richItalicFontSizePx on the wire");
        Assert(json.Contains("\"richBoldItalicFontSizePx\":23", StringComparison.Ordinal), "richBoldItalicFontSizePx on the wire");
        Assert(json.Contains("\"richBoldFontSpacingPx\":1", StringComparison.Ordinal), "richBoldFontSpacingPx on the wire");
        Assert(json.Contains("\"richItalicFontSpacingPx\":2", StringComparison.Ordinal), "richItalicFontSpacingPx on the wire");
        Assert(json.Contains("\"richBoldItalicFontSpacingPx\":3", StringComparison.Ordinal), "richBoldItalicFontSpacingPx on the wire");

        var plain = Serialize(Delta(Node("a")));
        Assert(!plain.Contains("\"richBold", StringComparison.Ordinal) && !plain.Contains("\"richItalic", StringComparison.Ordinal),
            "all nine role fields omitted for a node the producer streamed none for (wire unchanged off rich scenes)");
    }

    // R19 WP-4 CLIP CONTENTS: same lesson as ContentKey / the role fonts — WireNodeDelta is an EXPLICIT
    // field-by-field projection, so a producer field the client's reader already waits for is SILENTLY DROPPED
    // unless FromNode lists it. `clipContents` is the flag that makes a non-painting layout container bound its
    // children (the ancient-event ContentContainer); it is a DIFFERENT Godot property from `clipChildren`, so
    // neither field can stand in for the other. It rides the wire only when TRUE — a false is the client default,
    // and omitting it is what keeps the bytes for the ~99% of nodes that do not clip byte-identical.
    private static void ClipContentsReachesTheWire()
    {
        var json = Serialize(Delta(Node("panel") with { ClipContents = true }));
        Assert(json.Contains("\"clipContents\":true", StringComparison.Ordinal),
            $"clipContents projected onto the wire; got: {json}");
        Assert(!json.Contains("\"clipChildren\"", StringComparison.Ordinal),
            "clipContents does NOT imply clipChildren (two different Godot properties)");

        Assert(!Serialize(Delta(Node("a"))).Contains("\"clipContents\"", StringComparison.Ordinal),
            "clipContents omitted for a non-clipping node (wire unchanged off the clipping containers)");
    }

    private static void FocusedReachesTheWire()
    {
        var focused = Serialize(Delta(Node("reward") with { Focused = true }));
        Assert(focused.Contains("\"focused\":true", StringComparison.Ordinal),
            $"authoritative focused:true projected onto the browser wire; got: {focused}");

        var unfocused = Serialize(Delta(Node("reward") with { Focused = false }));
        Assert(!unfocused.Contains("\"focused\"", StringComparison.Ordinal),
            "authoritative focused:false omitted as the browser's false default");
        Assert(!Serialize(Delta(Node("plain"))).Contains("\"focused\"", StringComparison.Ordinal),
            "focus omitted when the producer cannot read it");
    }

