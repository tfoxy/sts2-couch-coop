    // R13: the SAME array carrying the second flight kind. Three entries, one per case both readers must agree on:
    // an explicit "discard" (the hand→discard fly, which also carries the resting angle it turns out of), a legacy
    // entry with neither key (what every shuffle entry still serializes to), and an entry whose kind this build has
    // never heard of — which must fail OPEN to the shuffle motion rather than being dropped, since dropping it would
    // leave a suppressed card frozen.
    private static void CardFlightDiscardDeltaFixtureMatches()
    {
        var flights = new List<CardFlightHintDelta>
        {
            new(TargetId: "61", TrailId: "62",
                Start: [960, 1180], End: [1740, 980], Control: [1350, 760], Basis: [1, 0, 0, 1],
                Speed0: 1.2, Accel: 2.1, Duration: 1.2, Scale0: 1, WindowMs: 3200,
                Kind: "discard", Rot0: -0.35),
            new(TargetId: "71", TrailId: null,
                Start: [300, 880], End: [1620, 880], Control: [960, 280], Basis: [1, 0, 0, 1],
                Speed0: 1.15, Accel: 2.4, Duration: 1.5, Scale0: 1, WindowMs: 3800),
            new(TargetId: "81", TrailId: null,
                Start: [1620, 880], End: [300, 880], Control: [960, 1480], Basis: [0.5, 0, 0, 0.5],
                Speed0: 1.1, Accel: 2, Duration: 1, Scale0: 0.5, WindowMs: 2800,
                Kind: "supernova", Rot0: 0.75),
        };
        var delta = new RuntimeSceneDelta(false, "run", "screen:run:live", [], [], null, CardFlights: flights);
        var json = Serialize(delta);

        // A shuffle entry's BYTES are the contract with already-deployed clients: adding the two fields must not add
        // a key to it. Asserted on the entry itself (not the whole payload, which does carry both keys elsewhere).
        var legacyEntry = json[json.IndexOf("\"71\"", StringComparison.Ordinal)..];
        legacyEntry = legacyEntry[..legacyEntry.IndexOf('}')];
        Assert(!legacyEntry.Contains("\"kind\"", StringComparison.Ordinal), "a shuffle entry writes no kind key");
        Assert(!legacyEntry.Contains("\"rot0\"", StringComparison.Ordinal), "a shuffle entry writes no rot0 key");

        // The discard entry carries both, camelCased like every other field.
        Assert(json.Contains("\"kind\":\"discard\"", StringComparison.Ordinal), "discard entry writes its kind");
        Assert(json.Contains("\"rot0\":-0.35", StringComparison.Ordinal), "discard entry writes its rot0");

        AssertOrWriteFixture("card-flight-discard-delta.json", json);
    }

