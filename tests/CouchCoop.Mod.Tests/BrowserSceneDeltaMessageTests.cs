    private static void Vector2SerializesFloatShortestRoundTrip()
    {
        // 0.1f promoted to double is 0.10000000149011612; the float cast must recover the shortest "0.1".
        var node = Node("a") with { Transform = new RuntimeSceneTransform2DSnapshot(V(1, 0), V(0, 1), V((double)0.1f, 128.5)) };
