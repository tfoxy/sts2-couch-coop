    // LINE2D STROKE GEOMETRY: the ContentKey / rich-role-font lesson again — WireNodeDelta is an EXPLICIT
    // field-by-field projection, so a producer field is SILENTLY DROPPED unless FromNode lists it, and the wire is
    // the ONLY place that can be caught (the static-field lockstep reflects over the producer record, never the DTO).
    // Prove all three reach the wire under the camelCase names both readers use, that an EMPTY points array (the
    // "stroke cleared" instruction) SURVIVES rather than being defaulted away, and that a node with none of them
    // (every node off the map) still omits all three so the wire elsewhere is byte-identical.
    private static void LineGeometryReachesTheWire()
    {
        var json = Serialize(Delta(Node("stroke") with
        {
            LinePoints = [17, 98, 457, 249],
            LineWidth = 12,
            LineColor = new RuntimeSceneColorSnapshot(1, 0, 0, 1, "#ff0000ff"),
        }));
        Assert(json.Contains("\"linePoints\":[17,98,457,249]", StringComparison.Ordinal),
            $"linePoints projected onto the wire as a flat array; got: {json}");
        Assert(json.Contains("\"lineWidth\":12", StringComparison.Ordinal), "lineWidth on the wire");
        Assert(json.Contains("\"lineColor\":{\"html\":\"#ff0000ff\"}", StringComparison.Ordinal),
            "lineColor on the wire, slimmed to html by the shared colour converter");

        // EMPTY is meaningful ("the stroke was cleared — erase it"), and must never be confused with omitted
        // ("unchanged — keep the retained geometry"). Nothing in the DTO may default it away.
        var cleared = Serialize(Delta(Node("stroke") with { LinePoints = [] }));
        Assert(cleared.Contains("\"linePoints\":[]", StringComparison.Ordinal),
            $"an EMPTY linePoints array survives to the wire (the clear/undo instruction); got: {cleared}");

        var plain = Serialize(Delta(Node("a")));
        Assert(!plain.Contains("\"line", StringComparison.Ordinal),
            "all three line fields omitted for a non-Line2D node (wire unchanged off the map)");
    }

