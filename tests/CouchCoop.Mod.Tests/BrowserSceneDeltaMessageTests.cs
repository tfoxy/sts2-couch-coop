    private static void FloatCastLosslessForProducerTransforms()
    {
        // The producer streams Godot float32 transforms promoted to double. Casting back to float and formatting
        // must recover a string that parses to the SAME float32 — no drift at the client's consumption precision.
        double[] samples = [(double)0.1f, (double)1.3125f, (double)959.5f, (double)-0.0009765625f, (double)1920f];
        foreach (var sample in samples)
        {
            var node = Node("a") with { Transform = new RuntimeSceneTransform2DSnapshot(V(1, 0), V(0, 1), V(sample, 0)) };
            var json = Serialize(Delta(node));
            // Extract the x we wrote and re-parse it as float; it must equal the source float32.
            var marker = "\"origin\":{\"x\":";
            var start = json.IndexOf(marker, StringComparison.Ordinal) + marker.Length;
            var end = json.IndexOf(',', start);
            var written = float.Parse(json[start..end], System.Globalization.CultureInfo.InvariantCulture);
            Assert(written == (float)sample, $"float round-trip lossless for {sample} (wrote {json[start..end]})");
        }
    }

    // GOLDEN: an exact expected JSON for a representative node — catches accidental field renames / reordering /
    // default-omission regressions. A node with a mix of default (omitted) and non-default (written) fields.
    private static void GoldenBytesForRepresentativeNode()
